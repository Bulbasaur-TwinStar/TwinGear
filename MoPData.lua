function TG:GetReadyDailyCooldowns()
    local ready = {}
    for _, cd in ipairs(DAILY_PROF_CDS) do
        if IsSpellKnown(cd.spell) then
            local start, duration = GetSpellCooldown(cd.spell)
            if not start or start == 0 or duration <= 1.5 then
                table.insert(ready, cd.tag)
            end
        end
    end
    return ready
end

function TG:GetMyWorldBosses()
    local res = {}
    for _, wb in ipairs(TG.WORLD_BOSSES) do
        table.insert(res, { name = wb.name, killed = IsQuestFlaggedCompleted(wb.q) and true or false })
    end
    return res
end

function TG:GetMyCurrencies()
    local res = {}
    for _, c in ipairs(TG.CURRENCIES) do
        local n, a, _, wk, wkMax = GetCurrencyInfo(c.id)
        table.insert(res, {
            id = c.id,
            label = (n and n ~= "" and n) or c.short,
            amount = a or 0,
            wk = wk or 0,
            wkMax = wkMax or 0
        })
    end
    return res
end

function TG:SaveCurrentAlt(d)
    if not d or not d.isSelf then return end
    TwinGearDB = TwinGearDB or {}; TwinGearDB.alts = TwinGearDB.alts or {}
    local p1, p2 = GetProfessions()
    local pr = {}
    for _, idx in ipairs({p1, p2}) do
        if idx then
            local n, _, r, m = GetProfessionInfo(idx)
            if n then table.insert(pr, { name = n, skill = r .. "/" .. m }) end
        end
    end
    local si = GetSpecialization()
    local specName = si and select(2, GetSpecializationInfo(si)) or ""
    local className, classToken = UnitClass("player")
    local rList = TG.GetMyRaids and TG:GetMyRaids() or {}
    local soo = rList[1] and string.format("SoO %d/%d", rList[1].clr or 0, rList[1].total or 14) or ""
    local key = (UnitName("player") or "Unknown") .. "-" .. (GetRealmName() or "TwinStar")
    TwinGearDB.alts[key] = {
        name = UnitName("player"), realm = GetRealmName(), classToken = classToken,
        spec = (specName ~= "" and (specName .. " ") or "") .. (className or ""), level = UnitLevel("player") or 90,
        ilvl = d.ilvl or 0, wb = TG:GetMyWorldBosses(), profs = pr, raid = soo,
        cds = TG:GetReadyDailyCooldowns()
    }
end

function TG:GetWeeklyExtras()
    local sealDone = (IsQuestFlaggedCompleted(33133) or IsQuestFlaggedCompleted(33134)) and true or false
    local ordosDone = IsQuestFlaggedCompleted(33118) and true or false
    local hasLegCloak = false
    local backLink = GetInventoryItemLink("player", 15)
    if backLink then
        local id = tonumber(string.match(backLink, "item:(%d+)"))
        if id and TG.LEGENDARY_CLOAKS and TG.LEGENDARY_CLOAKS[id] then hasLegCloak = true end
    end
    return sealDone, ordosDone, hasLegCloak
end

